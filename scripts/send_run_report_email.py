def _text_report(
    summary: RunSummary,
    publications: list[Publication],
    report_path: Path | None,
) -> str:
    extracted, history, snapshot, _ = _dataset_totals(summary)
    lines = [
        "PAISÓMETRO — INFORME AUTOMÁTICO DE PUBLICACIÓN",
        f"Estado: {_job_status().upper()}",
        f"Ejecución: #{summary.run_id}",
        f"LOOKBACK_PERIOD: {summary.lookback}",
        f"Valores extraídos: {extracted}",
        f"Escrituras en history.db: {history}",
        f"Valores en snapshot.db: {snapshot}",
        "",
        "DATASETS",
    ]
    for item in summary.datasets:
        issue = f" | Incidencias: {'; '.join(item.issues)}" if item.issues else ""
        lines.append(
            f"- {item.name}: {item.status}; {item.extracted} extraídos; "
            f"{item.history} history; {item.snapshot} snapshot{issue}"
        )
    lines.extend(("", "FICHEROS PUBLICADOS"))
    for item in publications:
        lines.append(f"- {item.label}: {item.state} -> {item.destination}")
    lines.extend(
        (
            "",
            f"Derivados materializados: {summary.derived_materialised}",
            f"Derivados omitidos: {summary.derived_skipped}",
            f"Informe local: {report_path or 'no disponible'}",
        )
    )
    return "\n".join(lines) + "\n"


def _send_email(
    summary: RunSummary,
    publications: list[Publication],
    report_path: Path | None,
) -> None:
    host = os.getenv("SMTP_HOST", "").strip()
    username = os.getenv("SMTP_USERNAME", "").strip()
    password = os.getenv("SMTP_PASSWORD", "")
    sender = os.getenv("SMTP_FROM", username).strip()
    recipients = [item.strip() for item in os.getenv("SMTP_TO", "").split(",") if item.strip()]
    if not host or not sender or not recipients:
        print("SMTP email not configured; notification skipped.")
        return

    repository = os.getenv("GITHUB_REPOSITORY", "Paisómetro")
    subject_prefix = os.getenv("SMTP_SUBJECT_PREFIX", "Paisómetro")
    subject = f"[{_job_status().upper()}] {subject_prefix} — data publication #{summary.run_id}"
    message = EmailMessage()
    message["Subject"] = subject
    message["From"] = sender
    message["To"] = ", ".join(recipients)
    message["X-Paisometro-Run"] = summary.run_id
    message.set_content(_text_report(summary, publications, report_path))
    message.add_alternative(_html_report(summary, publications, report_path), subtype="html")

    port = int(os.getenv("SMTP_PORT", "465"))
    use_tls = _env_bool("SMTP_USE_TLS", port != 465)
    if port == 465 and not use_tls:
        with smtplib.SMTP_SSL(host, port, timeout=30) as client:
            if username:
                client.login(username, password)
            client.send_message(message)
    else:
        with smtplib.SMTP(host, port, timeout=30) as client:
            client.ehlo()
            if use_tls:
                client.starttls()
                client.ehlo()
            if username:
                client.login(username, password)
            client.send_message(message)
    print(f"Publication email sent to {len(recipients)} recipient(s) for {repository}.")


def main() -> int:
    runtime_dir = Path(os.getenv("RUNTIME_DIR", ".runtime"))
    summary, report_path = _read_report(runtime_dir)
    publications = _load_publications()
    _load_publication_states(publications, runtime_dir)
    if not _should_send(publications):
        print("No publication changes detected; notification skipped.")
        return 0
    try:
        _send_email(summary, publications, report_path)
    except (OSError, smtplib.SMTPException, ValueError) as exc:
        print(f"Could not send publication email: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
