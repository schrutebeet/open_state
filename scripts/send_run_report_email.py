"""Send a formal email report for one GitHub Actions data publication run.

The script intentionally uses only Python's standard library.  It reads the
human-readable report generated by ``run_pipeline()``, compares publication
files with the pre-run hashes saved by the workflow, and sends both HTML and
plain-text email through any SMTP provider.
"""

from __future__ import annotations

import hashlib
import html
import os
import re
import smtplib
import sqlite3
import sys
from dataclasses import dataclass, field
from email.message import EmailMessage
from pathlib import Path

INDICATOR_RE = re.compile(
    r"^\s*-\s+(?P<code>.+?): requested (?P<requested>\d+); "
    r"extracted (?P<extracted>\d+); history DB written (?P<history>\d+); "
    r"snapshot DB contains (?P<snapshot>\d+)"
)
DATASET_RE = re.compile(r"^\[(?P<status>[A-Z]+)\]\s+(?P<dataset>.+)$")


@dataclass
class DatasetSummary:
    name: str
    status: str
    indicators: int = 0
    requested: int = 0
    extracted: int = 0
    history: int = 0
    snapshot: int = 0
    issues: list[str] = field(default_factory=list)


@dataclass
class RunSummary:
    status: str = "unknown"
    run_id: str = "unknown"
    started: str = "unknown"
    completed: str = "unknown"
    lookback: str = "unknown"
    datasets: list[DatasetSummary] = field(default_factory=list)
    derived_materialised: str = "0"
    derived_skipped: str = "0"
    sources: dict[str, list[str]] = field(default_factory=dict)


@dataclass
class Publication:
    label: str
    local_path: Path
    destination: str
    before_hash: str | None = None
    after_hash: str | None = None
    state: str = "not available"
    meaningful_change: bool = False


def _env_bool(name: str, default: bool = False) -> bool:
    value = os.getenv(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "y", "on"}


def _read_report(report_dir: Path) -> tuple[RunSummary, Path | None]:
    reports = sorted(report_dir.glob("run_report_*.txt"), key=lambda path: path.stat().st_mtime)
    report_path = reports[-1] if reports else None
    summary = RunSummary()
    if report_path is None:
        return summary, None

    current: DatasetSummary | None = None
    for raw_line in report_path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if line.startswith("Run:"):
            summary.run_id = line.partition(":")[2].strip()
        elif line.startswith("Status:"):
            summary.status = line.partition(":")[2].strip()
        elif line.startswith("Started:"):
            summary.started = line.partition(":")[2].strip()
        elif line.startswith("Collection completed:"):
            summary.completed = line.partition(":")[2].strip()
        elif line.startswith("LOOKBACK_PERIOD requested:"):
            summary.lookback = line.partition(":")[2].strip()
        elif line.startswith("DERIVED INDICATORS"):
            current = None
        elif line.startswith("Materialised:"):
            summary.derived_materialised = line.partition(":")[2].strip()
        elif line.startswith("Skipped:"):
            summary.derived_skipped = line.partition(":")[2].strip()

        dataset_match = DATASET_RE.match(line)
        if dataset_match:
            current = DatasetSummary(
                name=dataset_match.group("dataset"),
                status=dataset_match.group("status"),
            )
            summary.datasets.append(current)
            summary.sources[current.name] = []
            continue

        indicator_match = INDICATOR_RE.match(raw_line)
        if indicator_match and current is not None:
            current.indicators += 1
            current.requested += int(indicator_match.group("requested"))
            current.extracted += int(indicator_match.group("extracted"))
            current.history += int(indicator_match.group("history"))
            current.snapshot += int(indicator_match.group("snapshot"))
        elif line.startswith("Issue:") and current is not None:
            current.issues.append(line.partition(":")[2].strip())
        elif line.startswith("Warning:") and current is not None:
            current.issues.append(line.partition(":")[2].strip())
        elif line.startswith("http") and current is not None:
            summary.sources[current.name].append(line)

    return summary, report_path


def _sha256(path: Path) -> str | None:
    if not path.is_file():
        return None
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _observation_count(path: Path) -> int | None:
    if not path.is_file():
        return None
    try:
        with sqlite3.connect(path) as connection:
            return int(connection.execute("SELECT COUNT(*) FROM observations").fetchone()[0])
    except sqlite3.Error:
        return None


def _load_publications() -> list[Publication]:
    private_bucket = os.getenv("R2_PRIVATE_BUCKET", "paisometro-private")
    public_bucket = os.getenv("R2_PUBLIC_BUCKET", "paisometro-public")
    snapshot_key = os.getenv("SNAPSHOT_R2_KEY", "backups/<run>/snapshot.db")
    return [
        Publication(
            "History database",
            Path(os.getenv("HISTORY_DB_PATH", "")),
            f"s3://{private_bucket}/history.db",
        ),
        Publication(
            "Snapshot database",
            Path(os.getenv("SNAPSHOT_DB_PATH", "")),
            f"s3://{private_bucket}/{snapshot_key}",
        ),
        Publication(
            "Budget execution JSON",
            Path(os.getenv("BUDGET_HISTORY_PATH", "")),
            f"s3://{public_bucket}/v1/budget_execution_history.json",
        ),
        Publication(
            "Dashboard JSON",
            Path(os.getenv("DASHBOARD_PATH", "")),
            f"s3://{public_bucket}/v1/paisometro-dashboard.json",
        ),
    ]


def _load_publication_states(publications: list[Publication], runtime_dir: Path) -> None:
    baseline_path = runtime_dir / "publication_baseline.json"
    try:
        import json

        baseline_payload = json.loads(baseline_path.read_text(encoding="utf-8"))
        baseline = baseline_payload.get("files", baseline_payload)
        baseline_observations = baseline_payload.get("history_observations")
    except (OSError, ValueError):
        baseline = {}
        baseline_observations = None

    for publication in publications:
        publication.before_hash = baseline.get(publication.label)
        publication.after_hash = _sha256(publication.local_path)
        if publication.after_hash is None:
            publication.state = "not generated"
        elif publication.before_hash is None:
            publication.state = "created or restored"
        elif publication.before_hash != publication.after_hash:
            publication.state = "updated"
        else:
            publication.state = "unchanged"

        # history.db contains ingestion metadata that changes every run.  Its
        # observation count is the meaningful signal for email notifications.
        if publication.label == "History database":
            current_observations = _observation_count(publication.local_path)
            if current_observations is not None and baseline_observations is not None:
                publication.meaningful_change = current_observations != int(baseline_observations)
                if publication.meaningful_change:
                    publication.state = (
                        f"updated ({current_observations - int(baseline_observations):+d} observations)"
                    )
            else:
                publication.meaningful_change = publication.after_hash is not None
        elif publication.label != "Snapshot database":
            publication.meaningful_change = publication.state in {
                "created or restored",
                "updated",
            }


def _job_status() -> str:
    return os.getenv("RUN_CONCLUSION", os.getenv("JOB_STATUS", "success")).lower()


def _should_send(publications: list[Publication]) -> bool:
    if not _env_bool("EMAIL_ONLY_ON_CHANGES", True):
        return True
    return _job_status() != "success" or any(
        publication.meaningful_change for publication in publications
    )


def _status_color(status: str) -> str:
    return {
        "success": "#157347",
        "partial": "#9a6700",
        "failed": "#b42318",
        "failure": "#b42318",
        "cancelled": "#667085",
    }.get(status.lower(), "#475467")


def _dataset_totals(summary: RunSummary) -> tuple[int, int, int, int]:
    return tuple(
        sum(getattr(dataset, attribute) for dataset in summary.datasets)
        for attribute in ("extracted", "history", "snapshot", "indicators")
    )  # type: ignore[return-value]


